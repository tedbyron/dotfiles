"""Print a @font-face rule for each WOFF2 file, reading its width, weight, and
style from the font's OS/2 table.

Usage: font-face.py FAMILY FILE...
"""

import sys
from pathlib import Path

from fontTools.ttLib import TTFont

# OS/2 usWidthClass to CSS font-stretch keywords
STRETCH = {
    1: "ultra-condensed",
    2: "extra-condensed",
    3: "condensed",
    4: "semi-condensed",
    5: "normal",
    6: "semi-expanded",
    7: "expanded",
    8: "extra-expanded",
    9: "ultra-expanded",
}

# OS/2 fsSelection bits
ITALIC = 1 << 0
OBLIQUE = 1 << 9


def font_face(family: str, path: Path) -> str:
    os2 = TTFont(path)["OS/2"]
    if os2.fsSelection & OBLIQUE:
        style = "oblique"
    elif os2.fsSelection & ITALIC:
        style = "italic"
    else:
        style = "normal"

    return f"""@font-face {{
  font-family: '{family}';
  font-display: swap;
  font-stretch: {STRETCH[os2.usWidthClass]};
  font-style: {style};
  font-weight: {os2.usWeightClass};
  src: url('./{path.name}') format('woff2');
}}
"""


def main() -> None:
    family, *files = sys.argv[1:]
    rules = [font_face(family, Path(file)) for file in sorted(files)]
    print(f"/* {family}, generated by the curlio flake. */\n")
    print("\n".join(rules), end="")


if __name__ == "__main__":
    main()
